CREATE TABLE IF NOT EXISTS stores (
 id INT AUTO_INCREMENT PRIMARY KEY, name VARCHAR(120) NOT NULL, address VARCHAR(255) NOT NULL DEFAULT '', created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS users (
 id INT AUTO_INCREMENT PRIMARY KEY, name VARCHAR(120) NOT NULL, email VARCHAR(190) NOT NULL UNIQUE, password_hash VARCHAR(255) NOT NULL,
 role ENUM('SUPER_ADMIN','ADMIN') NOT NULL, store_id INT NULL, active BOOLEAN NOT NULL DEFAULT TRUE, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (store_id) REFERENCES stores(id)
);
CREATE TABLE IF NOT EXISTS products (
 id INT AUTO_INCREMENT PRIMARY KEY, store_id INT NOT NULL, name VARCHAR(120) NOT NULL, sku VARCHAR(60) NOT NULL, category VARCHAR(80) NOT NULL,
 price DECIMAL(14,2) NOT NULL, cost DECIMAL(14,2) NOT NULL, stock INT NOT NULL DEFAULT 0, reorder_level INT NOT NULL DEFAULT 5, color VARCHAR(30) NOT NULL DEFAULT 'blue', active BOOLEAN NOT NULL DEFAULT TRUE,
 UNIQUE KEY store_sku (store_id,sku), FOREIGN KEY (store_id) REFERENCES stores(id), INDEX (store_id,active)
);
CREATE TABLE IF NOT EXISTS customers (
 id INT AUTO_INCREMENT PRIMARY KEY, store_id INT NOT NULL, name VARCHAR(120) NOT NULL, email VARCHAR(190) NOT NULL DEFAULT '', phone VARCHAR(30) NOT NULL DEFAULT '', created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (store_id) REFERENCES stores(id)
);
CREATE TABLE IF NOT EXISTS sales (
 id INT AUTO_INCREMENT PRIMARY KEY, store_id INT NOT NULL, user_id INT NOT NULL, customer_id INT NULL, subtotal DECIMAL(14,2) NOT NULL, discount DECIMAL(14,2) NOT NULL DEFAULT 0, total DECIMAL(14,2) NOT NULL,
 request_key CHAR(36) NULL UNIQUE, request_fingerprint CHAR(64) NULL,
 payment ENUM('Cash','Card','Transfer') NOT NULL, status ENUM('COMPLETED','VOID') NOT NULL DEFAULT 'COMPLETED', created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(store_id) REFERENCES stores(id), FOREIGN KEY(user_id) REFERENCES users(id), FOREIGN KEY(customer_id) REFERENCES customers(id), INDEX(store_id,created_at)
);
CREATE TABLE IF NOT EXISTS sale_items (
 id INT AUTO_INCREMENT PRIMARY KEY, sale_id INT NOT NULL, product_id INT NOT NULL, product_name VARCHAR(120) NOT NULL, quantity INT NOT NULL, unit_price DECIMAL(14,2) NOT NULL, unit_cost DECIMAL(14,2) NOT NULL,
 FOREIGN KEY(sale_id) REFERENCES sales(id), FOREIGN KEY(product_id) REFERENCES products(id)
);
CREATE TABLE IF NOT EXISTS stock_movements (
 id INT AUTO_INCREMENT PRIMARY KEY, store_id INT NOT NULL, product_id INT NOT NULL, user_id INT NOT NULL, quantity INT NOT NULL, reason VARCHAR(255) NOT NULL, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(store_id) REFERENCES stores(id), FOREIGN KEY(product_id) REFERENCES products(id), FOREIGN KEY(user_id) REFERENCES users(id)
);
CREATE TABLE IF NOT EXISTS audit_logs (
 id INT AUTO_INCREMENT PRIMARY KEY, user_id INT NOT NULL, action VARCHAR(255) NOT NULL, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, FOREIGN KEY(user_id) REFERENCES users(id)
);
CREATE TABLE IF NOT EXISTS login_limits (
 limit_key CHAR(64) PRIMARY KEY, attempts INT NOT NULL DEFAULT 0, window_start DATETIME NOT NULL
);
